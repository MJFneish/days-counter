#!/usr/bin/env node
/**
 * Writes the Android app's icon set — the Lucide icons v1 used (lucide-react-native 1.60.0) — as
 * SVG path data in app/src/main/java/com/devlance/dayscounter/ui/icons/LucideIcons.kt, drawn by
 * `LucideIcon` (ui/icons/Lucide.kt). Downloads the SVGs of lucide-static at the same version from
 * unpkg; <rect>, <circle>, <line>, <polyline>… become plain paths so Compose's PathParser can read
 * them. Node built-ins only (Node 18+ for fetch).
 *
 * Usage (in android/):  yarn build:lucide
 * To add an icon: add its Lucide name below, re-run, and use LucideIcons.<Name>.
 *
 * (The iOS app uses SF Symbols instead — the platform's own icon set, as Mawakit does.)
 */
const fs = require('fs');
const path = require('path');

const VERSION = '1.60.0';
const ICONS = [
  // Tabs and screens
  'hourglass', 'settings-2', 'plus', 'pin', 'party-popper', 'calendar-clock', 'calendar-days', 'clock',
  'check', 'info', 'trash-2', 'x', 'contrast', 'history', 'moon', 'sun', 'timer', 'layout-grid',
  'lock', 'circle', 'circle-check',
  // The countdown icons (calendar-days is "calendar")
  'star', 'heart', 'cake', 'plane', 'graduation-cap', 'briefcase', 'house', 'baby', 'trophy', 'gift', 'flag',
];

const out = path.join(__dirname, '..', 'app', 'src', 'main', 'java', 'com', 'devlance', 'dayscounter', 'ui', 'icons', 'LucideIcons.kt');

const num = v => Number(v);
const attrs = text => Object.fromEntries([...text.matchAll(/([\w-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));

/** One SVG element as path data. */
function toPath(tag, a) {
  switch (tag) {
    case 'path':
      return a.d;
    case 'line':
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(num);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle': {
      const [cx, cy, r] = [num(a.cx), num(a.cy), num(a.r)];
      return `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`;
    }
    case 'ellipse': {
      const [cx, cy, rx, ry] = [num(a.cx), num(a.cy), num(a.rx), num(a.ry)];
      return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
    }
    case 'rect': {
      const [x, y, w, h] = [num(a.x ?? 0), num(a.y ?? 0), num(a.width), num(a.height)];
      const rx = Math.min(num(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(num(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
      return (
        `M${x + rx} ${y}H${x + w - rx}A${rx} ${ry} 0 0 1 ${x + w} ${y + ry}V${y + h - ry}` +
        `A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h}H${x + rx}A${rx} ${ry} 0 0 1 ${x} ${y + h - ry}` +
        `V${y + ry}A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`
      );
    }
    default:
      throw new Error(`unsupported <${tag}>`);
  }
}

const kotlinName = name => name.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');

async function main() {
  const entries = [];
  for (const name of ICONS) {
    const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    const svg = (await res.text()).replace(/<!--[\s\S]*?-->/g, '');
    const paths = [...svg.matchAll(/<(path|rect|circle|ellipse|line|polyline|polygon)\b([^>]*?)\/?>/g)].map(m => toPath(m[1], attrs(m[2])));
    if (paths.length === 0) throw new Error(`${name}: no shapes`);
    entries.push(`  val ${kotlinName(name)} = LucideIconData(\n${paths.map(d => `    ${JSON.stringify(d)},`).join('\n')}\n  )`);
  }
  const kotlin = `// GENERATED by android/scripts/build-lucide.js from lucide-static ${VERSION} — don't edit by hand.
// Lucide icons, ISC License, Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022
// as part of Feather (MIT); all other copyright (c) for Lucide are held by Lucide Contributors 2022.
package com.devlance.dayscounter.ui.icons

/** Lucide's 24×24 stroke icons as path data (stroke 2, round caps and joins, no fill). */
object LucideIcons {
${entries.join('\n\n')}
}
`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, kotlin);
  console.log(`wrote ${ICONS.length} icons to ${path.relative(path.join(__dirname, '..'), out)}`);
}

main().catch(err => {
  console.error(err.message);
  process.exit(1);
});
